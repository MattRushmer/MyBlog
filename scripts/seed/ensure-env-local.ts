import { randomBytes } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import bcrypt from "bcryptjs";

const BCRYPT_COST = 12;

/**
 * If .env.local doesn't exist yet, generates a fresh random admin password
 * and session secret and writes a working local-mode .env.local - so
 * `npm run seed && npm run dev` gives a usable /admin without a manual
 * hash-password step first. The password is never a hardcoded default: a
 * new one is generated per install and printed once, here, only.
 *
 * If .env.local already exists, it's left untouched - this never
 * overwrites an admin password someone has already set.
 */
export async function ensureEnvLocal(projectRoot: string): Promise<void> {
  const envPath = path.join(projectRoot, ".env.local");

  try {
    await fs.access(envPath);
    console.log(".env.local already exists - leaving your admin credentials as they are.");
    return;
  } catch {
    // Doesn't exist yet - fall through and create it.
  }

  const password = randomBytes(15).toString("base64url");
  const passwordHash = await bcrypt.hash(password, BCRYPT_COST);
  const sessionSecret = randomBytes(32).toString("hex");

  const contents = `# Generated by \`npm run seed\` on ${new Date().toISOString()}
DEPLOY_TARGET=local
SITE_URL=http://localhost:3000
MAX_UPLOAD_BYTES=15728640
UPLOAD_TICKET_TTL_SECONDS=300
SESSION_TTL_SECONDS=43200

ADMIN_USERNAME=admin
ADMIN_PASSWORD_HASH=${passwordHash}
SESSION_SECRET=${sessionSecret}
DATA_DIR=./data
UPLOADS_DIR=./data/uploads
`;

  await fs.writeFile(envPath, contents, "utf-8");

  console.log("");
  console.log("Created .env.local with a new local admin account:");
  console.log(`  username: admin`);
  console.log(`  password: ${password}`);
  console.log("This password is only shown once and is not stored anywhere in plaintext.");
  console.log("Change it later with: npm run hash-password -- \"new-password\"");
  console.log("");
}
